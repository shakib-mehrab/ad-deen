// Regenerates every Android icon for Ad-Deen from ONE master file: assets/logo/ad-deen-logo.svg
//
//   cd scripts/icons && npm install && npm run icons
//
// Outputs (relative to repo root):
//   assets/logo/ad-deen-logo-1024.png                       master raster (1024x1024)
//   assets/logo/play-store-512.png                          Play Store icon (512x512)
//   app/src/main/res/drawable/ic_launcher_background.xml    adaptive background (vector)
//   app/src/main/res/drawable/ic_launcher_foreground.xml    adaptive foreground (vector, safe zone)
//   app/src/main/res/drawable/ic_launcher_monochrome.xml    Android 13+ themed icon (vector)
//   app/src/main/res/drawable/ic_app_logo.xml               in-app logo (vector, no background)
//   app/src/main/res/mipmap-anydpi-v26/ic_launcher(_round).xml
//   app/src/main/res/mipmap-<density>/ic_launcher(_round).png   legacy icons (API < 26)
//   app/src/main/res/drawable-<density>/ic_stat_notification.png white-on-transparent status bar icon
import sharp from 'sharp';
import { readFileSync, writeFileSync, mkdirSync, rmSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const MASTER = join(ROOT, 'assets', 'logo', 'ad-deen-logo.svg');
const RES = join(ROOT, 'app', 'src', 'main', 'res');
// Strip XML comments first: the master's documentation comment mentions the group tags,
// and must never be mistaken for the real groups.
const svg = readFileSync(MASTER, 'utf8').replace(/<!--[\s\S]*?-->/g, '');

// ---------- SVG parsing (paths only, see rules in the master SVG) ----------
function group(id) {
  const m = svg.match(new RegExp(`<g id="${id}">([\\s\\S]*?)</g>`));
  if (!m) throw new Error(`Master SVG is missing <g id="${id}">`);
  return m[1];
}
function paths(groupBody) {
  const out = [];
  for (const m of groupBody.matchAll(/<path\b([\s\S]*?)\/>/g)) {
    const attrs = m[1];
    const get = (n) => (attrs.match(new RegExp(`\\b${n}="([^"]*)"`)) || [])[1];
    const d = get('d');
    if (!d) continue;
    out.push({ d: d.replace(/\s+/g, ' ').trim(), fill: get('fill') || '#000000', evenOdd: get('fill-rule') === 'evenodd' });
  }
  return out;
}
const bgPaths = paths(group('background'));
const fgPaths = paths(group('foreground'));
// Guard against the regression that shipped blank icons: the foreground must contain real artwork.
if (fgPaths.length === 0 || fgPaths.some((p) => p.d === bgPaths[0]?.d)) {
  throw new Error('Foreground group parsed incorrectly - check assets/logo/ad-deen-logo.svg');
}
console.log(`Parsed ${bgPaths.length} background path(s), ${fgPaths.length} foreground path(s)`);

// ---------- Vector drawables ----------
function vectorXml(list, { size = 108, viewport = 108, tx = 0, ty = 0, color } = {}) {
  const body = list.map((p) =>
    `        <path\n            android:fillColor="${color || p.fill}"${p.evenOdd ? '\n            android:fillType="evenOdd"' : ''}\n            android:pathData="${p.d}" />`
  ).join('\n');
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by scripts/icons/generate-icons.mjs from assets/logo/ad-deen-logo.svg. Do not edit by hand. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="${size}dp"
    android:height="${size}dp"
    android:viewportWidth="${viewport}"
    android:viewportHeight="${viewport}">
    <group android:translateX="${tx}" android:translateY="${ty}">
${body}
    </group>
</vector>
`;
}
function write(rel, content) {
  const file = join(RES, rel);
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content);
  console.log('  wrote', rel);
}

console.log('==> Vector drawables');
write('drawable/ic_launcher_background.xml', vectorXml(bgPaths));
write('drawable/ic_launcher_foreground.xml', vectorXml(fgPaths));
write('drawable/ic_launcher_monochrome.xml', vectorXml(fgPaths, { color: '#FFFFFFFF' }));
// In-app logo: logo artwork only, cropped to the 60-unit box around it (x/y 24..84)
write('drawable/ic_app_logo.xml', vectorXml(fgPaths, { size: 128, viewport: 60, tx: -24, ty: -24 }));

const adaptive = `<?xml version="1.0" encoding="utf-8"?>
<!-- GENERATED by scripts/icons/generate-icons.mjs. Do not edit by hand. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />
</adaptive-icon>
`;
write('mipmap-anydpi-v26/ic_launcher.xml', adaptive);
write('mipmap-anydpi-v26/ic_launcher_round.xml', adaptive);

// ---------- Raster outputs ----------
// Render the master with a cropped viewBox (x0..x0+span) at the given pixel size.
function cropped(svgText, x0, span) {
  return svgText.replace(/viewBox="[^"]*"/, `viewBox="${x0} ${x0} ${span} ${span}"`);
}
const fullSvg = svg;
const whiteFgSvg = svg
  .replace(/<g id="background">[\s\S]*?<\/g>/, '')
  .replace(/(<g id="foreground">[\s\S]*?<\/g>)/, (g) => g.replace(/fill="#[0-9A-Fa-f]{3,8}"/g, 'fill="#FFFFFF"'));

async function png(svgText, px, outFile, mask) {
  // Rasterise at 4x the target size, then downscale for clean anti-aliased edges.
  const sized = svgText.replace(/<svg([^>]*?)\swidth="\d+"\s+height="\d+"/, `<svg$1 width="${px * 4}" height="${px * 4}"`);
  let img = sharp(Buffer.from(sized)).resize(px, px);
  if (mask) {
    const r = mask === 'circle' ? px / 2 : Math.round(px * 0.18);
    const m = Buffer.from(`<svg width="${px}" height="${px}"><rect width="${px}" height="${px}" rx="${r}" ry="${r}" fill="#fff"/></svg>`);
    img = sharp(await img.png().toBuffer()).composite([{ input: m, blend: 'dest-in' }]);
  }
  mkdirSync(dirname(outFile), { recursive: true });
  await img.png().toFile(outFile);
  console.log('  wrote', outFile.replace(ROOT + '\\', '').replace(ROOT + '/', ''));
}

console.log('==> Master rasters');
await png(fullSvg, 1024, join(ROOT, 'assets', 'logo', 'ad-deen-logo-1024.png'));
await png(cropped(fullSvg, 6, 96), 512, join(ROOT, 'assets', 'logo', 'play-store-512.png'));

console.log('==> Legacy launcher icons (API 24-25)');
const launcherSizes = { mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 };
for (const [density, px] of Object.entries(launcherSizes)) {
  // Crop to the central 76 units so the artwork fills a legacy icon like other apps do.
  await png(cropped(fullSvg, 16, 76), px, join(RES, `mipmap-${density}`, 'ic_launcher.png'), 'rounded');
  await png(cropped(fullSvg, 16, 76), px, join(RES, `mipmap-${density}`, 'ic_launcher_round.png'), 'circle');
}

console.log('==> Notification icon (white on transparent, 24dp)');
const notifSizes = { mdpi: 24, hdpi: 36, xhdpi: 48, xxhdpi: 72, xxxhdpi: 96 };
for (const [density, px] of Object.entries(notifSizes)) {
  await png(cropped(whiteFgSvg, 22, 64), px, join(RES, `drawable-${density}`, 'ic_stat_notification.png'));
}

// Remove files from the previous logo pipeline so they cannot shadow the new ones.
for (const stale of [
  'drawable/ic_launcher_foreground_img.png',
  'drawable/ic_stat_notification.png',
  'drawable/ic_notification_logo.xml',
]) {
  const f = join(RES, stale);
  if (existsSync(f)) { rmSync(f); console.log('  removed stale', stale); }
}
console.log('==> Done.');
